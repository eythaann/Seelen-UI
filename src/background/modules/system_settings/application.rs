/// Package resources (pri) of the Settings app, used to resolve the `@{windows?ms-resource://...}`
/// strings of its search index when the `windows` pseudo-package can't be resolved directly.
const SETTINGS_APP_PRI: &str =
    r"SystemResources\Windows.UI.SettingsAppThreshold\Windows.UI.SettingsAppThreshold.pri";
/// "All Control Panel Items" shell folder, with a fallback to the legacy control panel folder.
const CONTROL_PANEL_FOLDERS: [&str; 2] = [
    r"::{26EE0668-A00A-44D7-9371-BEB064C98683}\0",
    r"::{21EC2020-3AEA-1069-A2DD-08002B30309D}",
];
/// Icon fonts installed on the system as (family, file in `%WINDIR%\Fonts`), Segoe Fluent Icons is Windows 11 only.
const SYSTEM_GLYPH_FONTS: [(&str, &str); 2] = [
    ("Segoe Fluent Icons", "SegoeIcons.ttf"),
    ("Segoe MDL2 Assets", "segmdl2.ttf"),
];
/// `OpenInNewWindow` (arrow link), present on all [`SYSTEM_GLYPH_FONTS`].
const GENERIC_SETTING_GLYPH: &str = "\u{E8A7}";
/// Folder inside the app cache where private fonts are copied, to be reachable by the webviews.
const FONTS_CACHE_FOLDER: &str = "system_fonts";

fn winrt_to_self(color: windows::UI::Color) -> Color {
    Color {
        r: color.R,
        g: color.G,
        b: color.B,
        a: color.A,
    }
}

fn srgb_to_linear(c: f64) -> f64 {
    if c <= 0.04045 {
        c / 12.92
    } else {
        ((c + 0.055) / 1.055).powf(2.4)
    }
}

fn linear_to_srgb(c: f64) -> f64 {
    if c <= 0.0031308 {
        c * 12.92
    } else {
        1.055 * c.powf(1.0 / 2.4) - 0.055
    }
}

/// Returns (L, C, H) in OKLCH — L in [0,1], C ≥ 0, H in [0°,360°).
fn rgb_to_oklch(r: u8, g: u8, b: u8) -> (f64, f64, f64) {
    let r = srgb_to_linear(r as f64 / 255.0);
    let g = srgb_to_linear(g as f64 / 255.0);
    let b = srgb_to_linear(b as f64 / 255.0);

    let l = 0.4121656120 * r + 0.5362752080 * g + 0.0514575653 * b;
    let m = 0.2118591070 * r + 0.6807189584 * g + 0.1074065790 * b;
    let s = 0.0883097947 * r + 0.2818474174 * g + 0.6302613616 * b;

    let l_ = l.cbrt();
    let m_ = m.cbrt();
    let s_ = s.cbrt();

    let ok_l = 0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_;
    let ok_a = 1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_;
    let ok_b = 0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_;

    let c = (ok_a * ok_a + ok_b * ok_b).sqrt();
    let h = ok_b.atan2(ok_a).to_degrees();
    let h = if h < 0.0 { h + 360.0 } else { h };

    (ok_l, c, h)
}

fn oklch_to_rgb(l: f64, c: f64, h: f64) -> (u8, u8, u8) {
    let h_rad = h.to_radians();
    let ok_a = c * h_rad.cos();
    let ok_b = c * h_rad.sin();

    let l_ = l + 0.3963377774 * ok_a + 0.2158037573 * ok_b;
    let m_ = l - 0.1055613458 * ok_a - 0.0638541728 * ok_b;
    let s_ = l - 0.0894841775 * ok_a - 1.2914855480 * ok_b;

    let lms_l = l_ * l_ * l_;
    let lms_m = m_ * m_ * m_;
    let lms_s = s_ * s_ * s_;

    let r = 4.0767416621 * lms_l - 3.3077115913 * lms_m + 0.2309699292 * lms_s;
    let g = -1.2684380046 * lms_l + 2.6097574011 * lms_m - 0.3413193965 * lms_s;
    let b = -0.0041960863 * lms_l - 0.7034186147 * lms_m + 1.7076147010 * lms_s;

    (
        (linear_to_srgb(r.clamp(0.0, 1.0)) * 255.0).round() as u8,
        (linear_to_srgb(g.clamp(0.0, 1.0)) * 255.0).round() as u8,
        (linear_to_srgb(b.clamp(0.0, 1.0)) * 255.0).round() as u8,
    )
}

/// Generates a 32-byte AccentPalette for the Windows registry.
/// 8 colors × 4 bytes (RGBA), ordered: accent_darkest … accent_lightest, complement.
/// Shades are generated by interpolating OKLCH lightness (perceptually uniform),
/// from 0.15 → base_L (indices 0-3) and base_L → 0.85 (indices 3-6).
/// The complement (index 7) keeps the same L and C with hue rotated 180°.
fn generate_accent_palette(color: seelen_core::system_state::Color) -> UIColors {
    let (l, c, h) = rgb_to_oklch(color.r, color.g, color.b);
    let mut palette = [0u8; 32];

    for i in 0usize..7 {
        // index 0 = lightest (accent_lightest), index 6 = darkest (accent_darkest)
        let j = 6 - i;
        let step_l = if j <= 3 {
            let t = j as f64 / 3.0;
            0.18 + t * (l - 0.18)
        } else {
            let t = (j - 3) as f64 / 3.0;
            l + t * (0.90 - l)
        };

        let (r, g, b) = oklch_to_rgb(step_l, c, h);
        let off = i * 4;
        palette[off] = r;
        palette[off + 1] = g;
        palette[off + 2] = b;
        palette[off + 3] = color.a;
    }

    // Complement: hue rotated 180°
    let (r, g, b) = oklch_to_rgb(l, c, (h + 180.0) % 360.0);
    palette[28] = r;
    palette[29] = g;
    palette[30] = b;
    palette[31] = color.a;

    UIColors::from_bytes(&palette)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SystemSettingsEvent {
    ColorChanged,
    TextScaleChanged,
    ColorSchemeSwitched,
}

pub struct SystemSettings {
    settings: UISettings,
    color_event_token: Option<i64>,
    text_scale_event_token: Option<i64>,
    is_dark_mode: std::sync::atomic::AtomicBool,
}

unsafe impl Send for SystemSettings {}

event_manager!(SystemSettings, SystemSettingsEvent);

impl SystemSettings {
    pub fn instance() -> &'static Self {
        static SYSTEM_SETTINGS: LazyLock<SystemSettings> = LazyLock::new(|| {
            let mut settings = SystemSettings::new();
            settings.init().log_error();
            settings
        });
        &SYSTEM_SETTINGS
    }

    fn new() -> Self {
        Self {
            settings: UISettings::new().expect("Failed to create UISettings"),
            color_event_token: None,
            text_scale_event_token: None,
            is_dark_mode: std::sync::atomic::AtomicBool::new(
                Self::read_dark_mode_from_registry().unwrap_or(false),
            ),
        }
    }

    fn init(&mut self) -> Result<()> {
        // Register color change event
        // Windows-rs clones the handler internally, so we don't need to store it
        let color_token = self
            .settings
            .ColorValuesChanged(&TypedEventHandler::new(Self::internal_on_colors_change))?;
        self.color_event_token = Some(color_token);

        // Register text scale change event
        let text_scale_token = self
            .settings
            .TextScaleFactorChanged(&TypedEventHandler::new(Self::internal_on_text_scale_change))?;
        self.text_scale_event_token = Some(text_scale_token);

        Ok(())
    }

    fn internal_on_colors_change(
        _listener: windows_core::Ref<UISettings>,
        _args: windows_core::Ref<IInspectable>,
    ) -> windows_core::Result<()> {
        let _ = Self::event_tx().send(SystemSettingsEvent::ColorChanged);

        if let Ok(is_dark) = Self::read_dark_mode_from_registry() {
            let previous = Self::instance()
                .is_dark_mode
                .swap(is_dark, std::sync::atomic::Ordering::SeqCst);
            if previous != is_dark {
                let _ = Self::event_tx().send(SystemSettingsEvent::ColorSchemeSwitched);
            }
        }

        Ok(())
    }

    fn internal_on_text_scale_change(
        _listener: windows_core::Ref<UISettings>,
        _args: windows_core::Ref<IInspectable>,
    ) -> windows_core::Result<()> {
        let _ = Self::event_tx().send(SystemSettingsEvent::TextScaleChanged);
        Ok(())
    }

    pub fn get_text_scale_factor(&self) -> Result<f64> {
        Ok(self.settings.TextScaleFactor()?)
    }

    pub fn set_accent_color(color: seelen_core::system_state::Color) -> Result<()> {
        log::info!(
            "Setting accent color to #{:02X}{:02X}{:02X}{:02X}",
            color.r,
            color.g,
            color.b,
            color.a
        );

        let hkcu = RegKey::predef(HKEY_CURRENT_USER);
        let key = hkcu.open_subkey_with_flags(
            r"Software\Microsoft\Windows\CurrentVersion\Explorer\Accent",
            winreg::enums::KEY_SET_VALUE,
        )?;
        // Registry stores the accent color as 0xAABBGGRR
        let dword: u32 = u32::from_be_bytes([color.a, color.b, color.g, color.r]);
        key.set_value("AccentColor", &dword)?;
        key.set_value("AccentColorMenu", &dword)?;
        key.set_value("StartColorMenu", &dword)?;

        let palette = generate_accent_palette(color);
        key.set_raw_value(
            "AccentPalette",
            &winreg::RegValue {
                bytes: palette.to_bytes().to_vec(),
                vtype: winreg::enums::REG_BINARY,
            },
        )?;

        WindowsApi::broadcast_setting_change("ImmersiveColorSet");
        Ok(())
    }

    fn read_dark_mode_from_registry() -> Result<bool> {
        let hkcu = RegKey::predef(HKEY_CURRENT_USER);
        let key =
            hkcu.open_subkey(r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize")?;
        let apps_use_light_theme: u32 = key.get_value("AppsUseLightTheme").unwrap_or(1);
        Ok(apps_use_light_theme == 0)
    }

    pub fn get_dark_mode(&self) -> Result<bool> {
        Self::read_dark_mode_from_registry()
    }

    pub fn set_dark_mode(enabled_dark: bool) -> Result<()> {
        log::info!("Setting dark mode to {enabled_dark}");

        let hkcu = RegKey::predef(HKEY_CURRENT_USER);
        let key = hkcu.open_subkey_with_flags(
            r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize",
            winreg::enums::KEY_SET_VALUE,
        )?;
        let dword: u32 = if enabled_dark { 0 } else { 1 };
        key.set_value("AppsUseLightTheme", &dword)?;
        key.set_value("SystemUsesLightTheme", &dword)?;

        WindowsApi::broadcast_setting_change("ImmersiveColorSet");
        Ok(())
    }

    pub fn get_colors(&self) -> Result<UIColors> {
        let settings = &self.settings;
        Ok(UIColors {
            accent_darkest: winrt_to_self(settings.GetColorValue(UIColorType::AccentDark3)?),
            accent_darker: winrt_to_self(settings.GetColorValue(UIColorType::AccentDark2)?),
            accent_dark: winrt_to_self(settings.GetColorValue(UIColorType::AccentDark1)?),
            accent: winrt_to_self(settings.GetColorValue(UIColorType::Accent)?),
            accent_light: winrt_to_self(settings.GetColorValue(UIColorType::AccentLight1)?),
            accent_lighter: winrt_to_self(settings.GetColorValue(UIColorType::AccentLight2)?),
            accent_lightest: winrt_to_self(settings.GetColorValue(UIColorType::AccentLight3)?),
            // https://learn.microsoft.com/is-is/uwp/api/windows.ui.viewmanagement.uisettings.getcolorvalue?view=winrt-19041#remarks
            complement: Color::default(),
        })
    }
}

impl Drop for SystemSettings {
    fn drop(&mut self) {
        if let Some(token) = self.color_event_token.take() {
            self.settings.RemoveColorValuesChanged(token).log_error();
        }

        if let Some(deferral) = self.text_scale_event_token.take() {
            self.settings
                .RemoveTextScaleFactorChanged(deferral)
                .log_error();
        }
    }
}

/// Searchable index of the Settings app pages and Control Panel applets, built once from
/// the Windows own indexes (already localized to the user's display language).
pub struct SystemSettingsIndex {
    entries: Vec<SystemSettingEntry>,
}

impl SystemSettingsIndex {
    pub fn instance() -> &'static Self {
        static INDEX: LazyLock<SystemSettingsIndex> = LazyLock::new(SystemSettingsIndex::build);
        &INDEX
    }

    pub fn entries(&self) -> &[SystemSettingEntry] {
        &self.entries
    }

    fn build() -> Self {
        let mut entries = Self::enum_settings_pages().unwrap_or_else(|e| {
            log::error!("Failed to enumerate settings pages: {e:?}");
            Vec::new()
        });
        entries.extend(Self::enum_control_panel_items().unwrap_or_else(|e| {
            log::error!("Failed to enumerate control panel items: {e:?}");
            Vec::new()
        }));
        log::trace!("System settings index built with {} entries", entries.len());
        Self { entries }
    }

    /// Reads `%WINDIR%\ImmersiveControlPanel\Settings\AllSystemSettings_{GUID}.xml`.
    fn enum_settings_pages() -> Result<Vec<SystemSettingEntry>> {
        let windir = SEELEN_COMMON.system_dir();
        let pri = windir.join(SETTINGS_APP_PRI);
        let pri = pri.to_string_lossy();

        let mut fonts = GlyphFonts::new(windir);
        let mut seen_files = HashSet::new();
        let mut seen_entries = HashSet::new();
        let mut entries = Vec::new();

        for file in std::fs::read_dir(windir.join(r"ImmersiveControlPanel\Settings"))? {
            let path = file?.path();
            let name = path.file_name().unwrap_or_default().to_string_lossy();
            if !name.starts_with("AllSystemSettings_") || !name.ends_with(".xml") {
                continue;
            }

            let content = std::fs::read_to_string(&path)?;
            let index: PcSettingsIndex =
                match quick_xml::de::from_str(content.trim_start_matches('\u{feff}')) {
                    Ok(index) => index,
                    Err(e) => {
                        log::warn!("Failed to parse {path:?}: {e}");
                        continue;
                    }
                };

            log::trace!("Reading {} settings from {path:?}", index.items.len());
            let mut unresolved = 0;
            for item in index.items {
                // some index files don't include the page ids, so only usable entries are marked as seen.
                let (Some(page), Some(info)) = (item.page(), &item.info) else {
                    continue;
                };

                // the same entries are repeated across the index files
                if !seen_files.insert(item.filename.clone()) {
                    continue;
                }

                let Some(title) = info
                    .description
                    .as_deref()
                    .and_then(|s| resolve_settings_string(s, &pri))
                else {
                    unresolved += 1;
                    continue;
                };

                let target = format!("ms-settings:{page}");
                if !seen_entries.insert((target.clone(), title.to_lowercase())) {
                    continue;
                }

                let keywords = [&info.high_keywords, &info.keywords]
                    .into_iter()
                    .flatten()
                    .filter_map(|s| resolve_settings_string(s, &pri))
                    .flat_map(|s| {
                        s.split(';')
                            .map(|k| k.trim().to_string())
                            .collect::<Vec<_>>()
                    })
                    .filter(|k| !k.is_empty())
                    .collect();

                let icon = item
                    .app_info
                    .as_ref()
                    .and_then(|info| fonts.resolve(info))
                    .unwrap_or_else(|| fonts.generic());

                entries.push(SystemSettingEntry {
                    kind: SystemSettingKind::Settings,
                    title,
                    description: None,
                    keywords,
                    target,
                    glyph: Some(icon.glyph),
                    font_family: Some(icon.font_family),
                    font_path: icon.font_path,
                });
            }

            if unresolved > 0 {
                log::trace!("{unresolved} settings titles could not be resolved in {path:?}");
            }
        }

        Ok(entries)
    }

    /// Enumerates the "All Control Panel Items" shell folder.
    fn enum_control_panel_items() -> Result<Vec<SystemSettingEntry>> {
        Com::run_with_context(|| {
            let folder = CONTROL_PANEL_FOLDERS
                .iter()
                .find_map(|f| WindowsApi::get_shell_item(Path::new(f)).ok())
                .ok_or("Control panel shell folder not found")?;

            let enumerator: IEnumShellItems =
                unsafe { folder.BindToHandler(None, &BHID_EnumItems)? };
            let mut entries = Vec::new();

            loop {
                let mut items = [None; 1];
                let mut fetched = 0u32;
                unsafe { enumerator.Next(&mut items, Some(&mut fetched))? };
                if fetched == 0 {
                    break;
                }

                let Some(item) = &items[0] else {
                    continue;
                };
                let item: IShellItem2 = item.cast()?;

                let title = unsafe { item.GetDisplayName(SIGDN_NORMALDISPLAY)?.to_string()? };
                let parsing_name = unsafe {
                    item.GetDisplayName(SIGDN_DESKTOPABSOLUTEPARSING)?
                        .to_string()?
                };
                let description = unsafe { item.GetString(&PKEY_InfoTipText) }
                    .ok()
                    .and_then(|s| unsafe { s.to_string() }.ok())
                    .filter(|s| !s.is_empty());

                entries.push(SystemSettingEntry {
                    kind: SystemSettingKind::ControlPanel,
                    title,
                    description,
                    keywords: Vec::new(),
                    target: format!("shell:{parsing_name}"),
                    glyph: None,
                    font_family: None,
                    font_path: None,
                });
            }

            Ok(entries)
        })
    }
}

/// Resolves the glyph fonts used by the Settings app search index.
struct GlyphFonts {
    windir: PathBuf,
    /// Family used for the generic glyph, the best one installed.
    generic_family: &'static str,
    /// Private font files already copied to the cache, by source path (`None` if the copy failed).
    copied: HashMap<String, Option<PathBuf>>,
}

impl GlyphFonts {
    fn new(windir: &Path) -> Self {
        let generic_family = SYSTEM_GLYPH_FONTS
            .iter()
            .find(|(_, file)| windir.join("Fonts").join(file).exists())
            .map_or(SYSTEM_GLYPH_FONTS[1].0, |(family, _)| family);

        Self {
            windir: windir.to_path_buf(),
            generic_family,
            copied: HashMap::new(),
        }
    }

    /// Same as the native search, entries using unavailable fonts or images get a generic glyph.
    fn generic(&self) -> GlyphIcon {
        GlyphIcon {
            glyph: GENERIC_SETTING_GLYPH.to_string(),
            font_family: self.generic_family.to_string(),
            font_path: None,
        }
    }

    fn resolve(&mut self, info: &ApplicationInformation) -> Option<GlyphIcon> {
        let glyph = info.glyph.clone().filter(|g| !g.is_empty())?;
        let font_family = info.font_family.clone()?;

        if SYSTEM_GLYPH_FONTS
            .iter()
            .any(|(family, _)| *family == font_family)
        {
            return Some(GlyphIcon {
                glyph,
                font_family,
                font_path: None,
            });
        }

        let source = info.font_file_path.as_ref()?;
        let font_path = self
            .copied
            .entry(source.clone())
            .or_insert_with(|| {
                let source = expand_windir(source, &self.windir);
                copy_font_to_cache(&source)
                    .inspect_err(|e| log::warn!("Failed to copy font {source:?}: {e:?}"))
                    .ok()
            })
            .clone()?;

        Some(GlyphIcon {
            glyph,
            font_family,
            font_path: Some(font_path),
        })
    }
}

struct GlyphIcon {
    glyph: String,
    font_family: String,
    font_path: Option<PathBuf>,
}

/// The webviews can't read from the Windows folder, so private fonts are served from the app cache.
fn copy_font_to_cache(source: &Path) -> Result<PathBuf> {
    let folder = SEELEN_COMMON.app_cache_dir().join(FONTS_CACHE_FOLDER);
    std::fs::create_dir_all(&folder)?;
    let target = folder.join(source.file_name().ok_or("Invalid font path")?);
    std::fs::copy(source, &target)?;
    Ok(target)
}

/// Expands the `%WINDIR%` variable used on the Settings app search index.
fn expand_windir(path: &str, windir: &Path) -> PathBuf {
    match path.get(..8) {
        Some(prefix) if prefix.eq_ignore_ascii_case("%WINDIR%") => {
            windir.join(path[8..].trim_start_matches('\\'))
        }
        _ => PathBuf::from(path),
    }
}

/// Resolves an indirect string of the Settings app search index, returns `None` if it can't be resolved.
fn resolve_settings_string(source: &str, settings_pri: &str) -> Option<String> {
    let source = source.trim();
    if !source.starts_with('@') {
        return (!source.is_empty()).then(|| source.to_string());
    }

    let resolved = WindowsApi::resolve_indirect_string(source)
        .ok()
        .filter(|s| !s.is_empty() && !s.starts_with("@{"))
        .or_else(|| {
            let uri = source.strip_prefix("@{windows?")?;
            WindowsApi::resolve_indirect_string(&format!("@{{{settings_pri}?{uri}")).ok()
        })?;

    let resolved = resolved.trim();
    (!resolved.is_empty() && !resolved.starts_with("@{")).then(|| resolved.to_string())
}
